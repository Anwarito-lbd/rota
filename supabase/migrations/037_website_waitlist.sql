-- Rota — 037 The website's waitlist and questions (therotaapp.com)
--
-- These two tables were first made by hand in the dashboard; this file
-- records them and closes the holes found on 2026-10-15:
--   · the same address could be signed up again and again, and every
--     insert sent a Rota e-mail: anyone could flood an inbox from our domain
--   · the welcome trigger posted the whole row to `send-welcome`, which
--     trusted whatever it was sent; it now gets only the row id and reads
--     the rest from the table (supabase/functions/send-welcome)
--   · no ceiling on sign-ups: a script could burn the Resend quota
--   · trigger functions were callable through the API
-- Safe to run more than once, and on a project that already has the tables.
-- ═════════════════════════════════════════════════════════════

create table if not exists public.waitlist (
  id bigint generated by default as identity primary key,
  email text not null,
  lang text,
  created_at timestamptz default now(),
  token uuid not null default gen_random_uuid(),
  confirmed boolean not null default false,
  confirmed_at timestamptz
);
create unique index if not exists waitlist_token_idx on public.waitlist (token);
alter table public.waitlist add column if not exists welcome_sent_at timestamptz;
create index if not exists waitlist_email_idx on public.waitlist (lower(email));
create index if not exists waitlist_created_idx on public.waitlist (created_at);

create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  email text not null,
  question text not null check (char_length(question) <= 300),
  lang text,
  created_at timestamptz default now()
);
create index if not exists questions_created_idx on public.questions (created_at);

alter table public.waitlist enable row level security;
alter table public.questions enable row level security;
drop policy if exists "anyone can add" on public.waitlist;
create policy "anyone can add" on public.waitlist for insert to anon, authenticated with check (true);
drop policy if exists "anyone can add" on public.questions;
create policy "anyone can add" on public.questions for insert to anon, authenticated with check (true);

-- Visitors can only add the fields the form sends; nobody can read, change or delete.
revoke all on public.waitlist, public.questions from anon, authenticated;
grant insert (email, lang) on public.waitlist to anon, authenticated;
grant insert (email, question, lang, created_at) on public.questions to anon, authenticated;

-- Before each sign-up: clean the address, ignore one already on the list
-- (no second e-mail, and no way to learn who signed up), and stop at
-- 30 sign-ups per 10 minutes for the whole site.
create or replace function public.waitlist_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  new.email := lower(trim(new.email));
  if char_length(new.email) > 254 or new.email !~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' then
    raise exception 'invalid_email';
  end if;
  new.lang := case when new.lang in ('fr', 'en', 'es') then new.lang else 'fr' end;
  new.created_at := now();
  if exists (select 1 from public.waitlist where lower(email) = new.email) then
    return null;
  end if;
  if (select count(*) from public.waitlist where created_at > now() - interval '10 minutes') >= 30 then
    raise exception 'busy';
  end if;
  return new;
end;
$$;
drop trigger if exists waitlist_guard on public.waitlist;
create trigger waitlist_guard before insert on public.waitlist
  for each row execute function public.waitlist_guard();

create or replace function public.questions_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  new.email := lower(trim(new.email));
  if char_length(new.email) > 254 or new.email !~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' then
    raise exception 'invalid_email';
  end if;
  new.lang := case when new.lang in ('fr', 'en', 'es') then new.lang else 'fr' end;
  new.created_at := now();
  if (select count(*) from public.questions where created_at > now() - interval '10 minutes') >= 20 then
    raise exception 'busy';
  end if;
  return new;
end;
$$;
drop trigger if exists questions_guard on public.questions;
create trigger questions_guard before insert on public.questions
  for each row execute function public.questions_guard();

-- After a sign-up: ask send-welcome to write, with the row id only.
create or replace function public.send_welcome_email()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform net.http_post(
    url := 'https://bbzdpiqjvnfcwvvygdys.supabase.co/functions/v1/send-welcome',
    headers := '{"Content-Type":"application/json"}'::jsonb,
    body := jsonb_build_object('id', new.id)
  );
  return new;
end;
$$;
drop trigger if exists on_waitlist_insert on public.waitlist;
create trigger on_waitlist_insert after insert on public.waitlist
  for each row execute function public.send_welcome_email();

-- Trigger functions run as triggers only, never through the API.
revoke execute on function public.waitlist_guard() from public, anon, authenticated;
revoke execute on function public.questions_guard() from public, anon, authenticated;
revoke execute on function public.send_welcome_email() from public, anon, authenticated;
do $$
begin
  if to_regprocedure('public.handle_new_user()') is not null then
    revoke execute on function public.handle_new_user() from public, anon, authenticated;
  end if;
  if to_regprocedure('public.rls_auto_enable()') is not null then
    revoke execute on function public.rls_auto_enable() from public, anon, authenticated;
  end if;
end;
$$;
